#<,>,=>,<= Relational operators
x = 100
y = 120
print("X and y is greater" if x>y else "Y is greater")

# == Comparison operator
a= 34
b = 345
print("a and b are equal " if a == b else "not equal")

# ** Exponentiation(Power) operator: use to calculate power of any number
print(5 ** 2) #25
print(10 ** 3) #100
print(2 ** 4) #16

# ^ Bitwise operator: compare the binary bits of numbers
print(5 ^ 3)
print(4 ^ 1)
